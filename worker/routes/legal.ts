function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function renderPage(title: string, subtitle: string, sections: Section[]): string {
  const body = sections
    .map(
      (sec) =>
        `<section><h2>${esc(sec.title)}</h2>${sec.body
          .map((p) => `<p>${esc(p)}</p>`)
          .join("")}</section>`,
    )
    .join("");
  return `<!DOCTYPE html>
<html lang="ko"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="index, follow">
<title>${esc(title)} · ${esc(META.serviceName)}</title>
<style>
  :root { color-scheme: light dark; }
  body { max-width: 720px; margin: 0 auto; padding: 24px 20px 64px; font-family: -apple-system, "Pretendard JP", "Pretendard", "Malgun Gothic", system-ui, sans-serif; line-height: 1.7; color: #1a1a1a; background: #fff; }
  @media (prefers-color-scheme: dark) { body { color: #e8e8e8; background: #121212; } }
  h1 { font-size: 22px; margin: 0 0 4px; }
  .sub { color: #666; font-size: 13px; margin: 0 0 24px; }
  @media (prefers-color-scheme: dark) { .sub { color: #9a9a9a; } }
  h2 { font-size: 16px; margin: 28px 0 8px; }
  p { font-size: 14px; margin: 0 0 6px; white-space: pre-line; }
  a { color: #d6336c; }
</style>
</head><body>
<h1>${esc(title)}</h1>
<p class="sub">${esc(subtitle)} · 최종 업데이트 ${esc(META.lastUpdated)}</p>
${body}
<p class="sub" style="margin-top:32px">문의: <a href="mailto:${esc(META.contactEmail)}">${esc(META.contactEmail)}</a></p>
</body></html>`;
}

